<?php
function gg_check($ok, $message) { if (!$ok) { throw new RuntimeException($message); } }
wp_set_current_user(1);
GG_Avito_Plugin::types();
GG_Avito_Plugin::routes();
GG_Avito_Plugin::demo(null);
GG_Avito_Plugin::demo(null);
$req = new WP_REST_Request('GET'); $req['page'] = 1;
$list = GG_Avito_Plugin::items($req);
gg_check($list['total'] === 2, 'Demo reimport created duplicates');
$item = $list['items'][0];
$settings = new WP_REST_Request('POST');
$settings->set_header('content-type', 'application/json');
$settings->set_body(wp_json_encode(['markup' => 10, 'update_fields' => ['price']]));
GG_Avito_Plugin::save_settings($settings);
$request = new WP_REST_Request('POST'); $request['id'] = $item['id']; $request['status'] = 'draft';
$result = GG_Avito_Plugin::publish($request);
$product = wc_get_product($result['product_id']);
gg_check($product->get_status() === 'draft', 'Product published without explicit action');
gg_check((float) $product->get_regular_price() === (float) $item['price'] * 1.1, 'Markup calculation failed');
$product->set_name('Manual website title'); $product->save();
GG_Avito_Plugin::publish($request);
$product = wc_get_product($result['product_id']);
gg_check($product->get_name() === 'Manual website title', 'Manual title overwritten');
gg_check((float) $product->get_regular_price() === (float) $item['price'] * 1.1, 'Markup compounded on update');
$request['status'] = 'publish'; GG_Avito_Plugin::publish($request);
$request['status'] = 'draft'; GG_Avito_Plugin::publish($request);
gg_check(get_post_status($result['product_id']) === 'publish', 'Published product demoted by draft action');
gg_check(count(get_posts(['post_type' => 'product', 'post_status' => 'any', 'numberposts' => -1])) === 1, 'Duplicate WooCommerce products');
$export = new WP_REST_Request('POST'); $export['ids'] = [$item['id']]; $export['format'] = 'zip';
$bundle = GG_Avito_Plugin::export($export);
$path = tempnam(sys_get_temp_dir(), 'gg-test'); file_put_contents($path, base64_decode($bundle['base64']));
$items = GG_Avito_Bundle::read($path, 'zip');
gg_check($items[0]['avito_id'] === $item['avito_id'], 'ZIP roundtrip lost source ID');
$job_id = wp_insert_post(['post_type' => 'gg_avito_job', 'post_status' => 'private', 'post_title' => 'Test job']);
update_post_meta($job_id, '_gg_job', wp_slash(['path' => $path, 'extension' => 'zip', 'items' => $items, 'pending' => [0], 'processed' => 0, 'errors' => [], 'skipped' => 0, 'replace' => false]));
$step = new WP_REST_Request('POST'); $step['id'] = $job_id;
$done = GG_Avito_Plugin::step($step);
gg_check($done['done'] && !$done['errors'], 'Import job failed');
gg_check(get_post_meta($job_id, '_gg_job', true)['skipped'] === 1, 'Existing item not skipped');
unlink($path);
wp_set_current_user(0);
$response = rest_do_request(new WP_REST_Request('GET', '/avito-gg/v1/state'));
gg_check(in_array($response->get_status(), [401, 403], true), 'Anonymous user can access admin data');
echo "WordPress/WooCommerce integration: passed\n";
